#!/usr/bin/env node
/**
 * Import the Shipyard scene media from a local ArkhEthos checkout.
 *
 *   node scripts/import-arkhethos-media.mjs --from <path-to-ArkhEthos> [--out <dir>] [--manifest <file>] [--check]
 *
 * Source of truth for what is imported is the file tables in plan/05-asset-manifest.md (path, bytes,
 * first 16 hex of sha256). Every file is read and verified BEFORE anything is written. On any
 * missing file, byte-count mismatch or hash mismatch the script writes nothing, names every
 * offending file with expected and actual values, and exits 1. Different bytes are different
 * assets (for example a meshopt-recompressed crew GLB), and the scene phase was measured against
 * the manifest bytes, so a near-match is not accepted.
 *
 * Writes <out>/{crew,ship-kit,ship-sound,ships}/... and <out>/LICENSES.md (from the manifest's
 * section headings). Default <out> is shipyard/public/media. `--check` verifies and writes nothing.
 * Exit codes: 0 imported/verified, 1 refused, 2 usage error.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const shipyardRoot = resolve(here, '..');
const DEFAULT_MANIFEST = join(shipyardRoot, 'plan', '05-asset-manifest.md');
const DEFAULT_OUT = join(shipyardRoot, 'public', 'media');

/** The manifest states these totals in prose; the parse must agree or the manifest is broken. */
const EXPECTED_FILES = 55;
const EXPECTED_BYTES = 12_410_762;

/**
 * Parse the manifest's `### \`dir/\` - licence` sections and their file tables.
 * @returns {{ sections: { dir: string, licence: string, files: { path: string, bytes: number, sha16: string }[] }[] }}
 */
export function parseManifest(text) {
  const sections = [];
  let current = null;
  for (const line of text.split(/\r?\n/)) {
    const head = line.match(/^###\s+`([a-z-]+)\/`\s+[—-]\s+(.*)$/);
    if (head) {
      current = { dir: head[1], licence: head[2].trim(), files: [] };
      sections.push(current);
      continue;
    }
    if (line.startsWith('#')) {
      current = null;
      continue;
    }
    const row = line.match(/^\|\s*`([a-z0-9-]+\/[^`]+)`\s*\|\s*(\d+)\s*\|\s*`([0-9a-f]{16})`\s*\|/i);
    if (row && current) current.files.push({ path: row[1], bytes: Number(row[2]), sha16: row[3].toLowerCase() });
  }
  return { sections };
}

function parseArgs(argv) {
  const out = { from: null, out: DEFAULT_OUT, manifest: DEFAULT_MANIFEST, check: false, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--from') out.from = argv[++i];
    else if (a === '--out') out.out = resolve(argv[++i] ?? '');
    else if (a === '--manifest') out.manifest = resolve(argv[++i] ?? '');
    else if (a === '--check') out.check = true;
    else if (a === '--help' || a === '-h') out.help = true;
    else return { error: `unknown argument: ${a}` };
  }
  return out;
}

/**
 * Prose the manifest does not carry: crew licence limits, per-piece kit packs, sound mapping and
 * provenance. Kept here so a re-run reproduces public/media/LICENSES.md byte for byte.
 */
const SECTION_NOTES = {
  crew: [
    'Owner-generated (Higgsfield gpt_image_2_5 sheet → sam_3_3d → Meshy rig), ArkhEthos ledger 2026-10-19; owner-owned, **not CC0 and not to be relicensed**. Reuse is limited to the owner\'s own Convenium.Design repository.',
  ],
  'ship-kit': [
    'Per piece (from `src/scene/ship-kit.json`): Kenney Modular Space Kit 1.0 = corridor-floor, corridor-wall, corridor-ceiling, airlock-frame, conduit-cables, wall-panel, support-pillar. Kenney Space Kit 2.0 = console-terminal, crew-seat, window-frame, cargo-barrels, railing. Quaternius Sci-Fi Essentials Kit (Standard) = locker, crate-large, tool-rack, workbench. Kenney Space Station Kit = pipe, pipe-ring, wall-display, hatch, floor-grate, container-tall, lectern, readout. Sources: kenney.nl/assets/modular-space-kit, kenney.nl/assets/space-kit, kenney.nl/assets/space-station-kit, quaternius.com/packs/scifiessentialskit.html.',
  ],
  'ship-sound': [
    'Per file: `hum.ogg` = Sci-Fi Sounds `spaceEngineLow_000`; `servo.ogg` = Sci-Fi Sounds `computerNoise_000`; `weld.ogg` = Sci-Fi Sounds `thrusterFire_000`; `click.ogg` = Interface Sounds `click_002`.',
  ],
};

const LICENCE_OVERRIDE = {
  ships: 'CC0 1.0 — Quaternius ship hulls (ArkhEthos PROGRESS 2026-10-18; the exact Quaternius pack name is not recorded in the manifest)',
};

const PROVENANCE =
  'Imported from a read-only snapshot of ArkhEthos revision `4de85a8`, not the owner\'s current checkout (`4db3cf3`, whose crew GLBs are meshopt-recompressed and do not match the manifest). Re-verified 2026-11-04: 55 files, 12,410,762 bytes, bytes and sha256 match `plan/05-asset-manifest.md`.';

export function licencesMarkdown(sections) {
  const lines = [
    '# Media licences',
    '',
    'Generated by `scripts/import-arkhethos-media.mjs` from `plan/05-asset-manifest.md`, then reviewed and extended on 2026-11-04 (source packs, sound mapping, provenance). Re-running the importer reproduces this file; edit the notes in the script, not the output.',
    '',
    'The crew GLBs and sheets were generated for the owner and are owner-owned, not CC0; the kit,',
    'hulls and sound are CC0 1.0. Everything was imported byte-for-byte from ArkhEthos and checked',
    'against the manifest (bytes and sha256).',
    '',
  ];
  for (const s of sections) {
    const notes = SECTION_NOTES[s.dir] ?? [];
    const licence = s.dir === 'crew' ? null : (LICENCE_OVERRIDE[s.dir] ?? s.licence);
    lines.push(`## \`${s.dir}/\``, '');
    if (licence) lines.push(licence, '');
    for (const n of notes) lines.push(n, '');
    lines.push(...s.files.map((f) => `- \`${f.path}\` (${f.bytes} bytes)`), '');
  }
  lines.push('## Provenance', '', PROVENANCE);
  return `${lines.join('\n')}\n`;
}

export function verifyAgainstManifest(fromRoot, sections) {
  const mediaRoot = join(fromRoot, 'public', 'media');
  const problems = [];
  const ok = [];
  for (const section of sections) {
    for (const f of section.files) {
      const abs = join(mediaRoot, f.path);
      if (!existsSync(abs)) {
        problems.push({ path: f.path, kind: 'missing', detail: `not found at ${abs}` });
        continue;
      }
      const buf = readFileSync(abs);
      const sha = createHash('sha256').update(buf).digest('hex');
      if (buf.length !== f.bytes || !sha.startsWith(f.sha16)) {
        problems.push({
          path: f.path,
          kind: 'mismatch',
          detail: `expected ${f.bytes} bytes sha256 ${f.sha16}; found ${buf.length} bytes sha256 ${sha.slice(0, 16)}`,
        });
        continue;
      }
      ok.push({ path: f.path, buf });
    }
  }
  return { problems, ok };
}

function main(argv) {
  const args = parseArgs(argv);
  if (args.error || args.help || !args.from) {
    console.error(args.error ? `${args.error}\n` : '');
    console.error('usage: node scripts/import-arkhethos-media.mjs --from <path-to-ArkhEthos> [--out <dir>] [--manifest <file>] [--check]');
    return args.help ? 0 : 2;
  }
  if (!existsSync(args.manifest)) {
    console.error(`manifest not found: ${args.manifest}`);
    return 2;
  }
  const { sections } = parseManifest(readFileSync(args.manifest, 'utf8'));
  const files = sections.flatMap((s) => s.files);
  const totalBytes = files.reduce((n, f) => n + f.bytes, 0);
  const usingDefaultManifest = args.manifest === DEFAULT_MANIFEST;
  if (usingDefaultManifest && (files.length !== EXPECTED_FILES || totalBytes !== EXPECTED_BYTES)) {
    console.error(`manifest parse disagrees with its own totals: ${files.length} files / ${totalBytes} bytes, expected ${EXPECTED_FILES} / ${EXPECTED_BYTES}`);
    return 2;
  }
  if (files.length === 0) {
    console.error('manifest lists no files');
    return 2;
  }

  const fromRoot = resolve(args.from);
  if (!existsSync(join(fromRoot, 'public', 'media'))) {
    console.error(`no public/media folder under ${fromRoot}; is that an ArkhEthos checkout?`);
    return 2;
  }

  const { problems, ok } = verifyAgainstManifest(fromRoot, sections);
  if (problems.length > 0) {
    console.error(`REFUSED: ${problems.length} of ${files.length} file(s) do not match plan/05-asset-manifest.md. Nothing was written.`);
    for (const p of problems) console.error(`  ${p.kind.toUpperCase().padEnd(8)} ${p.path}: ${p.detail}`);
    console.error('\nImport from the ArkhEthos revision the manifest was measured at (4de85a8), or re-measure the manifest and update it first.');
    return 1;
  }

  const bytes = ok.reduce((n, f) => n + f.buf.length, 0);
  if (args.check) {
    console.log(`OK (check only): ${ok.length} files, ${bytes} bytes match the manifest. Nothing was written.`);
    return 0;
  }
  for (const f of ok) {
    const dest = join(args.out, f.path);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, f.buf);
  }
  writeFileSync(join(args.out, 'LICENSES.md'), licencesMarkdown(sections), 'utf8');
  console.log(`IMPORTED ${ok.length} files, ${bytes} bytes into ${args.out} (+ LICENSES.md). All matched the manifest.`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
